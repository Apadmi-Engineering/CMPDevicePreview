import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.LIST
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.STRING
import com.squareup.kotlinpoet.TypeSpec
import com.squareup.kotlinpoet.joinToCode
import groovy.json.JsonSlurper
import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Generates the library's built-in `DevicePresets` catalog from the JSON device specs (copied from
 * flutter_device_preview), one `DevicePreset` property per spec, written with KotlinPoet. The specs'
 * fold display features and `systemUi.platform` are accepted and ignored.
 */
@CacheableTask
abstract class GenerateDevicePresetsTask : DefaultTask() {

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val specFiles: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        // Sorted by id, so `fold-8` precedes `fold-8-ultra`.
        val files = specFiles.files.sortedBy { it.nameWithoutExtension }
        if (files.isEmpty()) throw GradleException("No device specs found")

        val ids = mutableSetOf<String>()
        val names = mutableMapOf<String, String>()
        val presets = files.map { file ->
            @Suppress("UNCHECKED_CAST")
            val spec = try {
                JsonSlurper().parse(file) as? Map<String, Any?>
            } catch (error: Exception) {
                throw GradleException("${file.name} is not valid JSON: ${error.message}", error)
            } ?: throw GradleException("${file.name} must contain a JSON object")
            val id = string(spec, "id", file.name)
            if ("$id.json" != file.name) {
                throw GradleException("${file.name} declares id \"$id\"; the file must be named \"$id.json\"")
            }
            if (!ids.add(id)) throw GradleException("Duplicate device id \"$id\" in ${file.name}")
            val name = kotlinName(spec, file.name)
            names.put(name, id)?.let { clash ->
                throw GradleException("${file.name}: property name \"$name\" collides with $clash")
            }
            preset(name, spec)
        }


        val file = FileSpec.builder(DEVICES_PACKAGE, "DevicePresets")
            .addFileComment(
                "GENERATED — DO NOT EDIT.\n\n" +
                    "Source: cmpdevicepreview/device_specs/*.json\n" +
                    "Regenerated by the generateDevicePresets Gradle task."
            )
            .indent("    ")
            .addType(catalog(presets))
            .build()

        val output = outputDirectory.get().asFile
        output.deleteRecursively()
        file.writeTo(output)
    }

    /** A preset's public property, and the private function that builds it. */
    private class Preset(val property: PropertySpec, val builder: FunSpec)

    private fun catalog(presets: List<Preset>): TypeSpec = TypeSpec.objectBuilder("DevicePresets")
        .addModifiers(KModifier.PUBLIC)
        .addKdoc(
            "%L",
            "The built-in device catalog: ${presets.size} devices, generated from the device specs\n" +
                "shared with flutter_device_preview — screen size, pixel ratio, safe areas, frame\n" +
                "artwork, status bar artwork and keyboard heights included."
        )
        .apply { presets.forEach { addProperty(it.property) } }
        .addProperty(
            PropertySpec.builder("all", LIST.parameterizedBy(DEVICE_PRESET), KModifier.PUBLIC)
                .addKdoc("All built-in presets, sorted by id.")
                .initializer(
                    CodeBlock.builder().apply {
                        add("listOf(\n")
                        indent()
                        for (preset in presets) add("%N,\n", preset.property)
                        unindent()
                        add(")")
                    }.build()
                )
                .build()
        )
        .addFunction(
            FunSpec.builder("byId")
                .addModifiers(KModifier.PUBLIC)
                .addKdoc("Returns the built-in preset with the given [id], or null.")
                .addParameter("id", STRING)
                .returns(DEVICE_PRESET.copy(nullable = true))
                .addStatement("return all.firstOrNull { it.id == id }")
                .build()
        )
        // One builder function per preset keeps each JVM method, and the object's static
        // initializer, far from the 64 KB method size limit.
        .apply { presets.forEach { addFunction(it.builder) } }
        .build()

    private fun preset(name: String, spec: Map<String, Any?>): Preset {
        val fileName = "${spec["id"]}.json"
        val displayName = string(spec, "name", fileName)
        val brand = spec["brand"]?.let { string(spec, "brand", fileName) }
        val year = spec["year"]?.let { it as? Int ?: throw GradleException("$fileName: \"year\" must be an integer") }
        val type = when (val platform = string(spec, "platform", fileName)) {
            "android", "fuchsia" -> "Android"
            "iOS" -> "Ios"
            "macOS", "windows", "linux" -> "Other"
            else -> throw GradleException("$fileName: unknown platform \"$platform\"")
        }
        val kind = when (val kind = spec["kind"] ?: "phone") {
            "phone", "tablet", "foldable", "desktop" -> (kind as String).replaceFirstChar { it.uppercaseChar() }
            else -> throw GradleException("$fileName: unknown kind \"$kind\"")
        }
        val size = map(spec["portraitSize"], "portraitSize", fileName)
        val width = number(size["width"], "portraitSize.width", fileName)
        val height = number(size["height"], "portraitSize.height", fileName)
        val pixelRatio = number(spec["devicePixelRatio"], "devicePixelRatio", fileName)
        if (width <= 0 || height <= 0 || pixelRatio <= 0) {
            throw GradleException("$fileName: portraitSize and devicePixelRatio must be positive")
        }

        val details = listOfNotNull(brand, year?.toString()).joinToString(", ")
        val summary = "${format(width)} × ${format(height)} at ${format(pixelRatio)}x"
        val devicePreset = call(
            DEVICE_PRESET,
            "id" to stringLiteral(string(spec, "id", fileName)),
            "name" to stringLiteral(displayName),
            "type" to CodeBlock.of("%T.%L", DEVICE_TYPE, type),
            "kind" to CodeBlock.of("%T.%L", DEVICE_KIND, kind),
            "brand" to brand?.let { stringLiteral(it) },
            "year" to year?.let { CodeBlock.of("%L", it.toString()) },
            "portraitSize" to pair(SIZE, width, height),
            "devicePixelRatio" to float(pixelRatio),
            "portraitSafeArea" to spec["portraitPadding"]?.let { insets(it, "portraitPadding", fileName) },
            "landscapeSafeArea" to spec["landscapePadding"]?.let { insets(it, "landscapePadding", fileName) },
            "frame" to spec["frame"]?.let { frame(map(it, "frame", fileName), fileName) },
            "systemUi" to spec["systemUi"]?.let { systemUi(map(it, "systemUi", fileName), fileName) },
            // The keyboard covers part of the screen's height in its orientation: the portrait
            // height in portrait, the portrait width in landscape.
            "portraitKeyboardHeight" to keyboardHeight(spec, "portraitKeyboardHeight", height, fileName)?.let(::float),
            "landscapeKeyboardHeight" to keyboardHeight(spec, "landscapeKeyboardHeight", width, fileName)?.let(::float),
        )
        val builder = FunSpec.builder("${name}Preset")
            .addModifiers(KModifier.PRIVATE)
            .returns(DEVICE_PRESET)
            .addStatement("return %L", devicePreset)
            .build()
        val property = PropertySpec.builder(name, DEVICE_PRESET, KModifier.PUBLIC)
            .addKdoc("%L", "$displayName${if (details.isEmpty()) "" else " ($details)"}: $summary.")
            .initializer("%N()", builder)
            .build()
        return Preset(property, builder)
    }

    private fun frame(frame: Map<String, Any?>, fileName: String): CodeBlock {
        val size = map(frame["size"], "frame.size", fileName)
        return call(
            DEVICE_FRAME,
            "size" to pair(
                SIZE,
                number(size["width"], "frame.size.width", fileName),
                number(size["height"], "frame.size.height", fileName),
            ),
            "screenOffset" to frame["screenOffset"]?.let {
                val offset = map(it, "frame.screenOffset", fileName)
                pair(
                    OFFSET,
                    number(offset["x"], "frame.screenOffset.x", fileName),
                    number(offset["y"], "frame.screenOffset.y", fileName),
                )
            },
            "screenPath" to frame["screenPath"]?.let {
                val path = it as? String ?: throw GradleException("$fileName: frame.screenPath must be a string")
                if (path.isEmpty()) null else stringLiteral(path)
            },
            "body" to artwork(artworkLines(frame["body"], "frame.body", fileName)),
        )
    }

    /** `systemUi`, minus its `platform`; empty bars are left out, and so is an empty `systemUi`. */
    private fun systemUi(systemUi: Map<String, Any?>, fileName: String): CodeBlock? {
        val bars = listOf("statusBar", "navigationBar").mapNotNull { key ->
            systemUi[key]?.let { bar(map(it, "systemUi.$key", fileName), key, fileName) }?.let { key to it }
        }
        if (bars.isEmpty()) return null
        return call(DEVICE_SYSTEM_UI, *bars.toTypedArray())
    }

    private fun bar(bar: Map<String, Any?>, key: String, fileName: String): CodeBlock? {
        val slots = listOf("leading", "center", "trailing").map { slot ->
            slot to artwork(artworkLines(bar[slot], "systemUi.$key.$slot", fileName))
        }
        if (slots.all { (_, artwork) -> artwork == null }) return null
        val insets = listOf("inset", "bottomInset").map { inset ->
            inset to bar[inset]?.let { number(it, "systemUi.$key.$inset", fileName) }?.let { value ->
                if (value < 0) throw GradleException("$fileName: systemUi.$key.$inset must not be negative")
                float(value)
            }
        }
        return call(SYSTEM_UI_BAR, *(slots + insets).toTypedArray())
    }

    private fun keyboardHeight(spec: Map<String, Any?>, key: String, extent: Double, fileName: String): Double? {
        val height = spec[key]?.let { number(it, key, fileName) } ?: return null
        if (height <= 0 || height > extent) {
            throw GradleException("$fileName: \"$key\" must be positive and at most ${format(extent)}")
        }
        return height
    }

    /** SVG artwork: a string, or an array of lines joined with newlines. Null when absent or empty. */
    private fun artworkLines(value: Any?, key: String, fileName: String): List<String>? {
        val lines = when (value) {
            null -> return null
            is String -> listOf(value)
            is List<*> -> value.map { it as? String ?: throw GradleException("$fileName: $key lines must be strings") }
            else -> throw GradleException("$fileName: $key must be a string or an array of strings")
        }
        return lines.takeUnless { it.isEmpty() || it.all(String::isEmpty) }
    }

    /** A `listOf(…).joinToString("\n")` expression, keeping the spec's lines for readability. */
    private fun artwork(lines: List<String>?): CodeBlock? {
        if (lines == null) return null
        return CodeBlock.builder().apply {
            add("listOf(\n")
            indent()
            for (line in lines) add("%L,\n", stringLiteral(line))
            unindent()
            add(").joinToString(\"\\n\")")
        }.build()
    }

    private fun insets(value: Any?, key: String, fileName: String): CodeBlock {
        val insets = map(value, key, fileName)
        val sides = listOf("left", "top", "right", "bottom").map { side ->
            CodeBlock.of("%L = %L", side, float(insets[side]?.let { number(it, "$key.$side", fileName) } ?: 0.0))
        }
        return CodeBlock.of("%T(%L)", DEVICE_INSETS, sides.joinToCode())
    }

    /**
     * The Kotlin property name of a spec, derived like the Flutter generator's Dart names: the brand
     * token is dropped and the rest camel-cased (`apple-iphone-16-pro` → `iPhone16Pro`,
     * `samsung-galaxy-z-fold-8` → `galaxyZFold8`).
     */
    private fun kotlinName(spec: Map<String, Any?>, fileName: String): String {
        val id = string(spec, "id", fileName)
        nameOverrides[id]?.let { return it }
        var tokens = id.split('-')
        val brand = (spec["brand"] as? String)?.lowercase()
        if (tokens.size > 1 && tokens.first() == brand) tokens = tokens.drop(1)
        val name = tokens.mapIndexed { index, raw ->
            val token = tokenSpellings[raw] ?: raw
            if (token.isEmpty()) throw GradleException("$fileName: id \"$id\" has an empty token")
            if (index == 0) token else token.replaceFirstChar { it.uppercaseChar() }
        }.joinToString("")
        if (!Regex("^[a-zA-Z_][a-zA-Z0-9_]*$").matches(name)) {
            throw GradleException(
                "$fileName: derived property name \"$name\" is not a valid identifier; " +
                    "add the id to nameOverrides in buildSrc/src/main/kotlin/GenerateDevicePresetsTask.kt"
            )
        }
        return name
    }

    private fun string(spec: Map<String, Any?>, key: String, fileName: String): String =
        spec[key] as? String ?: throw GradleException("$fileName: \"$key\" must be a string")

    @Suppress("UNCHECKED_CAST")
    private fun map(value: Any?, key: String, fileName: String): Map<String, Any?> =
        value as? Map<String, Any?> ?: throw GradleException("$fileName: \"$key\" must be an object")

    private fun number(value: Any?, key: String, fileName: String): Double =
        (value as? Number)?.toDouble() ?: throw GradleException("$fileName: \"$key\" must be a number")

    private fun format(value: Double): String =
        if (value == Math.floor(value) && Math.abs(value) < 1e9) value.toLong().toString() else value.toString()

    private fun float(value: Double): CodeBlock = CodeBlock.of("%Lf", format(value))

    /** `Type(first, second)`, for `Size` and `Offset`. */
    private fun pair(type: ClassName, first: Double, second: Double): CodeBlock =
        CodeBlock.of("%T(%L, %L)", type, float(first), float(second))

    /** A constructor call with one named argument per line; an argument whose value is null is left out. */
    private fun call(type: ClassName, vararg arguments: Pair<String, CodeBlock?>): CodeBlock =
        CodeBlock.builder().apply {
            add("%T(\n", type)
            indent()
            for ((name, value) in arguments) if (value != null) add("%N = %L,\n", name, value)
            unindent()
            add(")")
        }.build()

    private fun stringLiteral(value: String): CodeBlock {
        // A JVM class file caps each string constant at 65535 bytes.
        if (value.toByteArray(Charsets.UTF_8).size > 60_000) {
            throw GradleException("A device spec string is too long to embed (${value.length} chars)")
        }
        return CodeBlock.of("%S", value)
    }

    private companion object {
        const val DEVICES_PACKAGE = "com.apadmi.cmpdevicepreview.devices"
        const val CORE_PACKAGE = "com.apadmi.cmpdevicepreview.core"

        val SIZE = ClassName("androidx.compose.ui.geometry", "Size")
        val OFFSET = ClassName("androidx.compose.ui.geometry", "Offset")
        val DEVICE_FRAME = ClassName(CORE_PACKAGE, "DeviceFrame")
        val DEVICE_INSETS = ClassName(CORE_PACKAGE, "DeviceInsets")
        val DEVICE_KIND = ClassName(CORE_PACKAGE, "DeviceKind")
        val DEVICE_PRESET = ClassName(CORE_PACKAGE, "DevicePreset")
        val DEVICE_SYSTEM_UI = ClassName(CORE_PACKAGE, "DeviceSystemUi")
        val DEVICE_TYPE = ClassName(CORE_PACKAGE, "DeviceType")
        val SYSTEM_UI_BAR = ClassName(CORE_PACKAGE, "SystemUiBar")

        /** Ids whose property name cannot be derived from the id itself. */
        val nameOverrides = mapOf(
            "desktop-small" to "smallDesktopWindow",
            "desktop-large" to "largeDesktopWindow",
        )

        /** Id tokens with a spelling other than plain capitalization. */
        val tokenSpellings = mapOf(
            "iphone" to "iPhone",
            "ipad" to "iPad",
        )
    }
}
